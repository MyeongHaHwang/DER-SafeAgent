"""Manuscript artifacts for E4 (Energy Impact estimator validation)."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

TAG = "ijcip_final_revision"
RES = Path("code/results") / TAG / "e4_estimator"
GEN = Path("paper/generated") / TAG
plt.rcParams.update({"font.size": 8, "figure.dpi": 150,
                     "axes.spines.top": False, "axes.spines.right": False})


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    m65 = json.loads((RES / "estimator_validation_h65.json").read_text())
    m600 = json.loads((RES / "estimator_validation_h600.json").read_text())
    df = pd.read_csv(RES / "counterfactual_rollouts_h600.csv")

    def row(label, k, fmt="{:.3f}"):
        a = m65.get(k); b = m600.get(k)
        f = lambda v: ("--" if v is None or (isinstance(v, float) and np.isnan(v))
                       else fmt.format(v))
        return f"{label} & {f(a)} & {f(b)} \\\\"

    body = "\n".join([
        row("Top-1 optimal-action accuracy", "top1_optimal_action_accuracy"),
        row("Spearman $\\rho$, curtailment", "spearman_curtailment"),
        row("Spearman $\\rho$, ENS", "spearman_ens"),
        row("MAE curtailment (kWh)", "mae_curtailment_kwh", "{:.2f}"),
        row("MAE ENS (kWh)", "mae_ens_kwh", "{:.2f}"),
        row("NRMSE curtailment", "nrmse_curtailment"),
        row("Median regret (kWh-eq.)", "median_regret", "{:.2f}"),
        row("95th-percentile regret (kWh-eq.)", "p95_regret", "{:.2f}"),
        row("Configurations with zero regret", "frac_scenarios_zero_regret"),
    ])
    tex = rf"""% Auto-generated by code/evaluation/final_revision/build_e4_artifacts.py
% Source: code/results/{TAG}/e4_estimator/estimator_validation_h{{65,600}}.json
\begin{{table}}[t]
\centering
\caption{{Counterfactual validation of the Energy Impact estimator.
Ground truth is obtained by branching the simulator at the mitigation instant
and executing \emph{{every}} candidate action under an identical exogenous
trajectory ({m600['n_counterfactual_rollouts']} rollouts over
{m600['n_scenarios']} configurations); it never consults the estimator being
evaluated. Two horizons are reported: $65$\,s, matching the estimator's own
stated response window, and $600$\,s, the incident duration over which the
decision consequence actually accrues. Regret is the realised cost of the
estimator's choice minus the cost of the best action, in kWh-equivalent units
(curtailment $+\,5\times$ENS $+\,1.0\times$voltage-excursion area).}}
\label{{tab:estimator-validation}}
\footnotesize
\begin{{tabular}}{{lcc}}
\toprule
Metric & $65$\,s horizon & $600$\,s horizon \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (GEN / "table_energy_estimator_validation.tex").write_text(tex)
    print(f"-> {GEN/'table_energy_estimator_validation.tex'}")

    # Figure: predicted vs realised cost, and regret distribution
    fig, axes = plt.subplots(1, 2, figsize=(6.8, 2.8))
    ax = axes[0]
    for act, g in df.groupby("action"):
        ax.scatter(g.pred_curt_kwh, g.true_curt_kwh, s=14, alpha=0.75,
                   label=act.replace("_", " "))
    lim = max(df.pred_curt_kwh.max(), df.true_curt_kwh.max()) * 1.05
    ax.plot([0, lim], [0, lim], "k--", lw=0.8)
    ax.set_xlabel("predicted curtailment (kWh)")
    ax.set_ylabel("realised curtailment (kWh)")
    ax.set_title("Estimator calibration (600 s)", fontsize=8)
    ax.legend(frameon=False, fontsize=5.5, loc="upper left")
    ax.grid(alpha=0.3, lw=0.5)

    ax = axes[1]
    per = df.groupby("scenario").estimator_regret.first().sort_values()
    ax.bar(range(len(per)), per.values, color="#C44E52")
    ax.set_xlabel("configuration (sorted)")
    ax.set_ylabel("regret (kWh-equivalent)")
    ax.set_title("Regret of the estimator's choice (600 s)", fontsize=8)
    ax.grid(axis="y", alpha=0.3, lw=0.5)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(GEN / f"figure_energy_estimator_calibration.{ext}",
                    bbox_inches="tight")
    plt.close(fig)
    print(f"-> {GEN/'figure_energy_estimator_calibration.pdf'}")


if __name__ == "__main__":
    main()
