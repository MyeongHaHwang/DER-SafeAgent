# --------------------------------------------------------------- Figure D
def figure_d_opendss_sensitivity() -> None:
    raw = pd.read_csv(RES / "opendss_sweep" / "raw_results.csv")
    live = raw[~raw.is_calibration_control & raw.converged_clean]
    fig, axes = plt.subplots(1, 3, figsize=(7.2, 2.4))
    panels = [("attack_magnitude", ["low", "med", "high"], "Attack magnitude"),
              ("der_penetration", ["low", "med", "high"], "DER penetration"),
              ("location_bus", None, "DER location (bus)")]
    dets = [("deterministic_energy_policy", "D0"), ("der_secagent_heuristic_k3", "H0"),
            ("rule_ids", "RID")]
    for ax, (key, order, title) in zip(axes, panels):
        levels = order or sorted(live[key].unique())
        levels = [l for l in levels if l in set(live[key])]
        x = np.arange(len(levels))
        w = 0.26
        for i, (det, short) in enumerate(dets):
            vals = [live[(live[key] == l) & (live.detector == det)].curt_kwh.mean()
                    for l in levels]
            ax.bar(x + (i - 1) * w, vals, w, label=short, color=PAL[short])
        ax.set_xticks(x, [str(l) for l in levels], rotation=0)
        ax.set_title(title, fontsize=8)
        ax.set_ylabel("Mean curtailment (kWh)" if key == "attack_magnitude" else "")
        ax.grid(axis="y", alpha=0.3, linewidth=0.5)
    axes[0].legend(frameon=False, fontsize=7)
    fig.suptitle("OpenDSS sweep (real power-flow solves; D0/H0/RID contain no LLM call)",
                 fontsize=8, y=1.04)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"fig_opendss_sensitivity.{ext}", bbox_inches="tight")
    plt.close(fig)
    print(f"Figure D -> {FIG/'fig_opendss_sensitivity.pdf'}")


# --------------------------------------------------------------- Figure A
def figure_a_stubfeeder_configs() -> None:
    p = RES / "llm_in_loop" / "llm_in_loop_summary.csv"
    if not p.exists():
        print("Figure A skipped (no llm_in_loop summary yet)")
        return
    df = pd.read_csv(p)
    order = [d for d in ("deterministic_energy_policy", "der_secagent_heuristic_k3",
                         "rule_ids", "bare_qwen_lora", "der_secagent_qwen_lora_k1",
                         "der_secagent_llama_lora_k1") if d in set(df.system)]
    scen = sorted(df.scenario.unique())
    fig, axes = plt.subplots(2, 1, figsize=(7.2, 5.2), sharex=True)
    for ax, metric, lab in zip(axes, ("ens_kwh", "curt_kwh"),
                               ("ENS (kWh)", "Curtailed energy (kWh)")):
        x = np.arange(len(scen))
        w = 0.8 / max(len(order), 1)
        for i, sysname in enumerate(order):
            sub = df[df.system == sysname].set_index("scenario")
            vals = [sub[metric].get(s, np.nan) for s in scen]
            short = sysname.split("_")[0][:3].upper()
            ax.bar(x + i * w - 0.4, vals, w,
                   label=LABEL.get(sysname, sysname).replace(r"\emph", "").replace(r"\textbf", "")
                   .replace("{", "").replace("}", ""))
        ax.set_ylabel(lab)
        ax.grid(axis="y", alpha=0.3, linewidth=0.5)
    axes[0].legend(frameon=False, fontsize=6, ncol=2)
    axes[1].set_xticks(np.arange(len(scen)),
                       [s.replace("rv13_", "").replace("rv34_", "34:") for s in scen],
                       rotation=90, fontsize=5)
    fig.suptitle(f"Per-configuration outcomes across {len(scen)} unique StubFeeder "
                 f"configurations (unit of inference = configuration)", fontsize=8)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"fig_stubfeeder_configs.{ext}", bbox_inches="tight")
    plt.close(fig)
    print(f"Figure A -> {FIG/'fig_stubfeeder_configs.pdf'}")


