    agg = pd.read_csv(RES / "opendss_sweep" / "aggregate_metrics.csv")
    axes = [("attack_magnitude", "Attack magnitude"),
            ("der_penetration", "DER penetration"),
            ("location_bus", "DER location (bus)"),
            ("load_level", "Load level")]
    lines = []
    for key, title in axes:
        sub = agg[agg.axis == key]
        lines.append(rf"\multicolumn{{5}}{{l}}{{\emph{{{title}}}}} \\")
        for level in sub.level.unique():
            s = sub[sub.level == level]
            cells = []
