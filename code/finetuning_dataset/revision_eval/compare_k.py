"""Fair K=1 vs K=3 comparison, restricted to the prompts both settings saw.

K=3 runs on the pre-registered subset, so comparing it against the full-corpus
K=1 numbers would confound the K setting with prompt difficulty. This script
intersects the two prediction sets by prompt id before computing anything, and
also reports how often the two settings simply agree — the quantity that
decides whether self-consistency is doing any work at all.

Run: python3 -m code.finetuning_dataset.revision_eval.compare_k
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

REVISION_TAG = "ijcip_revision_r1r2_20260805"
RES = Path("code/results") / REVISION_TAG / "lora_eval"
TAB = Path("paper/tables")

PAIRS = [("qwen2_5_7b_lora", "qwen2_5_7b_lora_k1", "qwen2_5_7b_lora_k3_subset48"),
         ("llama3_1_8b_lora", "llama3_1_8b_lora_k1", "llama3_1_8b_lora_k3_subset48")]


def _load(tag: str) -> dict[str, dict] | None:
    p = RES / tag / "predictions.jsonl"
    if not p.exists():
        return None
    return {r["id"]: r for r in map(json.loads, p.read_text().splitlines()) if r}


def _metrics(rows: list[dict]) -> dict:
    return {
        "class_acc": float(np.mean([r["pred_class"] == r["true_class"] for r in rows])),
        "proposed_acc": float(np.mean([r["proposed_action"] == r["expected_action"] for r in rows])),
        "final_acc": float(np.mean([r["final_action"] == r["expected_action"] for r in rows])),
        "schema": float(np.mean([r["schema_ok"] for r in rows])),
        "json": float(np.mean([r["json_valid"] for r in rows])),
        "latency_s": float(np.mean([r["latency_ms"] for r in rows])) / 1000.0,
        "irrev_proposed": int(sum(r["proposed_action"] == "isolate_inverter" for r in rows)),
        "irrev_executed": int(sum(r["final_action"] == "isolate_inverter" for r in rows)),
    }


def main() -> None:
    rows = []
    for backend, tag1, tag3 in PAIRS:
        k1, k3 = _load(tag1), _load(tag3)
        if not k1 or not k3:
            print(f"[skip] {backend}: missing K=1 or K=3 predictions")
            continue
        shared = sorted(set(k1) & set(k3))
        a = [k1[i] for i in shared]
        b = [k3[i] for i in shared]
        m1, m3 = _metrics(a), _metrics(b)
        agree_cls = int(sum(x["pred_class"] == y["pred_class"] for x, y in zip(a, b)))
        agree_act = int(sum(x["final_action"] == y["final_action"] for x, y in zip(a, b)))
        for k, m in (("1", m1), ("3", m3)):
            rows.append({"backend": backend, "K": k, "n_shared": len(shared),
                         **m,
                         "agree_class_with_other_K": agree_cls,
                         "agree_final_action_with_other_K": agree_act})
        print(f"{backend}  (n={len(shared)} shared prompts)")
        for k, m in (("K=1", m1), ("K=3", m3)):
            print(f"  {k}: class={m['class_acc']:.3f} proposed={m['proposed_acc']:.3f} "
                  f"final={m['final_acc']:.3f} schema={m['schema']:.3f} "
                  f"lat={m['latency_s']:.1f}s irrev={m['irrev_proposed']}/{m['irrev_executed']}")
        print(f"  agreement: class {agree_cls}/{len(shared)}, "
              f"final action {agree_act}/{len(shared)}")

    if not rows:
        return
    df = pd.DataFrame(rows)
    out = RES / "k1_vs_k3_matched.csv"
    df.to_csv(out, index=False)

    body = []
    for backend, tag1, tag3 in PAIRS:
        sub = df[df.backend == backend]
        if sub.empty:
            continue
        for _, r in sub.iterrows():
            body.append(" & ".join([
                backend.replace("_", r"\_") if r.K == "1" else "",
                f"$K{{=}}{r.K}$", str(int(r.n_shared)),
                f"{r.class_acc:.3f}", f"{r.proposed_acc:.3f}", f"{r.final_acc:.3f}",
                f"{r.schema:.3f}", f"{r.latency_s:.1f}",
                f"{int(r.irrev_proposed)}/{int(r.irrev_executed)}",
                (f"{int(r.agree_class_with_other_K)}/{int(r.n_shared)}"
                 if r.K == "3" else ""),
            ]) + r" \\")
    tex = rf"""% Auto-generated by code/finetuning_dataset/revision_eval/compare_k.py
\begin{{table}}[t]
\centering
\caption{{$K{{=}}1$ versus $K{{=}}3$ self-consistency, compared only on the
prompts both settings saw (the $K{{=}}3$ runs use the pre-registered subset, so
comparing against full-corpus $K{{=}}1$ numbers would confound the $K$ setting
with prompt difficulty). ``Agree'' counts prompts on which the two settings
predict the same attack class --- the quantity that decides whether
self-consistency is doing any work. ``Irrev.'' is the irreversible
\texttt{{isolate\_inverter}} primitive, proposed / executed.}}
\label{{tab:k1-vs-k3}}
\scriptsize
\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{llrccccccc}}
\toprule
Backbone & $K$ & $n$ & Class acc. & Prop.\ act. & Final act. & Schema & Lat.\ (s) & Irrev. & Agree \\
\midrule
{chr(10).join(body)}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (TAB / "table_k1_vs_k3.tex").write_text(tex)
    print(f"\n-> {out}\n-> {TAB/'table_k1_vs_k3.tex'}")


if __name__ == "__main__":
    main()
